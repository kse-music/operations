import { lstat, readdir, readFile } from 'node:fs/promises';
import path from 'node:path';

async function requireEntry(root, relative, directory = false) {
  const target = path.join(root, relative);
  const info = await lstat(target).catch((cause) => {
    throw new Error(`Incomplete system plugin: missing ${target}`, { cause });
  });
  if (info.isSymbolicLink() || !(directory ? info.isDirectory() : info.isFile()))
    throw new Error(
      `System plugin ${directory ? 'directory' : 'file'} must not be a link: ${target}`,
    );
}

export async function discoverSystemPlugins(root) {
  const directory = path.join(root, 'plugins/system');
  await requireEntry(root, 'plugins/system', true);
  const plugins = [];
  const identities = new Set();
  for (const name of (await readdir(directory)).sort()) {
    const source = `plugins/system/${name}`;
    const info = await lstat(path.join(root, source));
    if (info.isSymbolicLink())
      throw new Error(`System plugin directory must not be a link: ${source}`);
    if (name === 'packages') {
      if (!info.isDirectory()) throw new Error('plugins/system/packages must be a directory');
      continue;
    }
    if (!info.isDirectory()) continue;
    if (!/^[a-z0-9-]+$/.test(name))
      throw new Error(`Invalid system plugin directory name: ${name}`);
    for (const folder of ['backend', 'backend/src'])
      await requireEntry(root, `${source}/${folder}`, true);
    for (const file of [
      'manifest.json',
      'backend/Cargo.toml',
      'backend/Cargo.lock',
      'backend/src/lib.rs',
    ])
      await requireEntry(root, `${source}/${file}`);
    const manifestPath = path.join(root, source, 'manifest.json');
    let manifest;
    try {
      manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
    } catch (cause) {
      throw new Error(`Cannot read system plugin manifest: ${manifestPath}`, { cause });
    }
    const id = manifest?.id;
    if (
      typeof id !== 'string' ||
      id.length > 80 ||
      !/^[a-z][a-z0-9-]*(?:\.[a-z][a-z0-9-]*)+$/.test(id)
    )
      throw new Error(`Invalid system plugin ID in ${source}/manifest.json`);
    if (identities.has(id)) throw new Error(`Duplicate system plugin ID: ${id}`);
    identities.add(id);
    if (manifest.entry?.ui) {
      const ui = manifest.entry.ui;
      if (
        typeof ui !== 'string' ||
        ui
          .split('/')
          .some((part) => !/^[a-zA-Z0-9_.-]+$/.test(part) || part === '.' || part === '..')
      )
        throw new Error(`Invalid system plugin UI entry in ${source}/manifest.json`);
      const folders = ui.split('/');
      folders.pop();
      for (let index = 1; index <= folders.length; index++)
        await requireEntry(root, `${source}/${folders.slice(0, index).join('/')}`, true);
      await requireEntry(root, `${source}/${ui}`);
      await requireEntry(root, `${source}/frontend`, true);
      await requireEntry(root, `${source}/frontend/main.ts`);
    }
    plugins.push({ name, id, source, destination: `plugins/system/packages/${name}.sdplugin` });
  }
  return plugins;
}

export function systemPluginRegistry(plugins) {
  const entries = plugins.map(
    ({ id, name }) => `    (${JSON.stringify(id)}, include_bytes!("${name}.sdplugin")),`,
  );
  return [
    '// Generated by tools/build-system-plugins.mjs. Do not edit.',
    `const PACKAGES: [(&str, &[u8]); ${plugins.length}] = [`,
    ...entries,
    '];',
    '',
  ].join('\n');
}
